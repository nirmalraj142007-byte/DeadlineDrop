#!/usr/bin/env bash
# EXPLAIN (ANALYZE, BUFFERS) for the hot queries, on 1,000 students and 1,000 submissions in mixed
# states. Starts the Compose postgres service, builds a throw-away database (dd_explain) from the
# Flyway migrations, seeds it, writes results/explain.md and drops the database again.
# Nothing in dd_c (the local app database) is touched.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "${ROOT}"
OUT="${ROOT}/results/explain.md"
DB="dd_explain"
DB_USER="${DB_USER:-$(grep -E '^DB_USER=' .env 2>/dev/null | cut -d= -f2- || true)}"
DB_USER="${DB_USER:-dd}"

psql_admin() { docker compose exec -T postgres psql -X -q -v ON_ERROR_STOP=1 -U "${DB_USER}" -d postgres "$@"; }
psql_db() { docker compose exec -T postgres psql -X -q -v ON_ERROR_STOP=1 -U "${DB_USER}" -d "${DB}" "$@"; }

echo "Starting the Compose postgres service..."
docker compose up -d --wait postgres

cleanup() { psql_admin -c "DROP DATABASE IF EXISTS ${DB} WITH (FORCE)" >/dev/null 2>&1 || true; }
trap cleanup EXIT

psql_admin -c "DROP DATABASE IF EXISTS ${DB} WITH (FORCE)" >/dev/null
psql_admin -c "CREATE DATABASE ${DB}" >/dev/null

echo "Applying Flyway migrations..."
for f in $(ls src/main/resources/db/migration/V*.sql | sort -V); do
  psql_db < "${f}" >/dev/null
done

echo "Seeding 1,000 students and 1,000 submissions..."
psql_db < tools/explain/seed.sql >/dev/null

# Pick real rows so every query has something to find.
scalar() { psql_db -At -c "$1"; }
STUDENT="$(scalar "SELECT student_id FROM submissions WHERE status = 'VERIFIED' AND student_id IN (SELECT student_id FROM submissions WHERE status = 'SUPERSEDED') ORDER BY student_id LIMIT 1")"
LIVE_KEY="$(scalar "SELECT idempotency_key FROM submissions WHERE student_id = '${STUDENT}' AND status = 'VERIFIED'")"
COMMITTED_ID="$(scalar "SELECT id FROM submissions WHERE status = 'COMMITTED' ORDER BY committed_at LIMIT 1")"
ASSIGNMENT="00000000-0000-0000-0003-000000000001"
COURSE="00000000-0000-0000-0002-000000000001"
VARS=(-v "student=${STUDENT}" -v "live_key=${LIVE_KEY}" -v "committed_id=${COMMITTED_ID}" -v "assignment=${ASSIGNMENT}" -v "course=${COURSE}")

# Turns "-- title: X" into a psql \echo so each plan gets a heading.
run_file() {
  local file="$1" prefix="$2"
  { echo "${prefix}"; sed -E "s/^-- title: (.*)$/\\\\echo '### \1'/" "${file}"; } | psql_db "${VARS[@]}"
}

# Reads psql output on stdin; after each "### " section appends which index served it and whether
# a sequential scan on submissions or jobs was chosen.
annotate() {
  awk '
    function flush() {
      if (title == "") return
      printf "%s", body
      idx = (n == 0) ? "none (no index scan in this plan)" : idxlist
      printf "```\n\n**Index used:** %s\n", idx
      printf "**Sequential scan on submissions or jobs:** %s\n\n", (seq ? "YES" : "no")
    }
    /^### / { flush(); title = $0; body = $0 "\n\n```text\n"; n = 0; idxlist = ""; seq = 0; next }
    title == "" { next }
    {
      body = body $0 "\n"
      if (match($0, /(Index Only Scan|Index Scan|Bitmap Index Scan)( Backward)?( using| on) [A-Za-z0-9_]+/)) {
        s = substr($0, RSTART, RLENGTH); sub(/.*(using|on) /, "", s)
        if (index(idxlist, s) == 0) { idxlist = idxlist (idxlist == "" ? "" : ", ") s; n++ }
      }
      if ($0 ~ /Seq Scan on (submissions|jobs)/) seq = 1
    }
    END { flush() }
  '
}

mkdir -p "$(dirname "${OUT}")"
{
  echo "# Query plans for the hot queries"
  echo
  echo "Generated by \`tools/explain.sh\` on $(date -u +%Y-%m-%dT%H:%M:%SZ) against PostgreSQL $(scalar 'SHOW server_version')."
  echo "Data: $(scalar 'SELECT count(*) FROM users WHERE role = $$STUDENT$$') students, $(scalar 'SELECT count(*) FROM submissions') submissions"
  echo "($(scalar "SELECT string_agg(status || ': ' || n, ', ' ORDER BY status) FROM (SELECT status, count(*) AS n FROM submissions GROUP BY status) t")),"
  echo "$(scalar 'SELECT count(*) FROM jobs') jobs. Statements that write are wrapped in BEGIN/ROLLBACK."
  echo "Execution times are from a Docker container on a laptop: compare plans, not milliseconds."
  echo
  for f in tools/explain/0*.sql; do
    run_file "${f}" "" | annotate
    # When the planner picked a sequential scan on a table this small, show that the index is still
    # usable by forbidding sequential scans for the same statement.
    if run_file "${f}" "" | grep -Eq 'Seq Scan on (submissions|jobs)'; then
      echo "#### Same statement with sequential scans disabled (shows the index is usable)"
      echo
      run_file "${f}" "SET enable_seqscan = off;" | annotate
    fi
  done
} > "${OUT}"

echo "Wrote ${OUT}"
